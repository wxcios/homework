test('long titles keep student fields and practice content separated on screen and print', async ({ page }) => {
  await page.goto('/')
  for (const subject of ['语文', '数学']) {
    await page.getByRole('radio', { name: subject, exact: true }).check()
    await page.getByText('20mm', { exact: true }).click()
    await page.locator('.sidebar-controls input.ant-input').first().fill('家庭作业'.repeat(10))
    for (const media of ['screen', 'print'] as const) {
      await page.emulateMedia({ media })
      const positions = await page.locator('.worksheet-sheet').first().evaluate(sheet => {
        const header = sheet.querySelector('.worksheet-header')!.getBoundingClientRect()
        const meta = sheet.querySelector('.worksheet-meta')!.getBoundingClientRect()
        const title = sheet.querySelector('h1')!.getBoundingClientRect()
        const content = sheet.querySelector('.chinese-practice, .math-problems')!.getBoundingClientRect()
        return { headerBottom: header.bottom, metaBottom: meta.bottom, titleBottom: title.bottom, metaTop: meta.top, contentTop: content.top }
      })
      expect(positions.titleBottom).toBeLessThanOrEqual(positions.metaTop)
      expect(positions.metaBottom).toBeLessThanOrEqual(positions.headerBottom)
      expect(positions.metaBottom).toBeLessThanOrEqual(positions.contentTop)
    }
    await page.emulateMedia({ media: 'screen' })
  }
})

